// ─── WhatsApp text formatter ──────────────────────────────────────────────────

function buildRxText(
  patient: Patient,
  visit: VisitRecord,
  doctorName: string,
  clinicName: string,
  address: string,
) {
  const lines: string[] = [];
  lines.push(`*${clinicName || doctorName}*`);
  if (address) lines.push(address);
  lines.push('');
  lines.push(`*Patient:* ${patient.name}  |  ${patient.age}y ${patient.gender}`);
  lines.push(`*MRN:* ${patient.mrn}  |  *Date:* ${new Date(visit.date).toLocaleDateString('en-IN')}`);
  lines.push(`*Dr:* ${visit.doctorName}`);
  lines.push('');
  lines.push(`*Diagnosis:* ${visit.diagnosis}`);

  if (visit.drugs.length > 0) {
    lines.push('');
    lines.push('*💊 Medications:*');
    visit.drugs.forEach((d, i) => {
      lines.push(`${i + 1}. ${d.drug} ${d.dose} — ${d.frequency}, ${d.duration}`);
      if (d.instructions) lines.push(`   _(${d.instructions})_`);
    });
  }

  if (visit.advice) {
    lines.push('');
    lines.push(`*Advice:* ${visit.advice}`);
  }

  if (visit.followUp) {
    lines.push(`*Follow-up:* ${visit.followUp}`);
  }

  lines.push('');
  lines.push('_Generated by Vyasa Integrated Healthcare_');
  return lines.join('\n');
}

